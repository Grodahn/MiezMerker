"""Generate adapters and support table from the append-only diagnostic catalog."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / 'diagnostics/error-codes.json').read_text(encoding='utf-8'))
cases = [(entry['operation'], entry['status']) for entry in catalog.values() if 'operation' in entry]
assert len(cases) == len(set(cases)), 'Duplicate diagnostic operation/status'
codes = [entry['code'] for entry in catalog.values()]
assert len(codes) == len(set(codes)), 'Duplicate diagnostic code'
assert all(re.fullmatch(r'MM-[A-Z]+-\d{3}', code) for code in codes)
ts = '// Generated by scripts/generate-error-codes.py; edit diagnostics/error-codes.json.\n'
ts += 'export const errorCodes = ' + json.dumps({key: row['code'] for key, row in catalog.items()}, indent=2) + ' as const;\n'
ts += 'export type ErrorCode = typeof errorCodes[keyof typeof errorCodes];\n'
java = 'package org.miezmerker.backend.diagnostics;\n\n'
java += '// Generated by scripts/generate-error-codes.py.\npublic final class ErrorCodes {\n    private ErrorCodes() {}\n'
for key, row in catalog.items():
    java += f'    public static final String {key} = "{row["code"]}";\n'
java += '    public static String operation(String operation, int status, String fallback) {\n        return switch (operation + ":" + status) {\n'
for key, row in catalog.items():
    if 'operation' in row:
        java += f'            case "{row["operation"]}:{row["status"]}" -> {key};\n'
java += '            default -> fallback;\n        };\n    }\n}\n'
doc = '''# Stable error codes (#194)

`diagnostics/error-codes.json` is authoritative. Add codes; never renumber, reuse,
or derive them from translated text. Regenerate adapters and this table with
`python scripts/generate-error-codes.py`; CI validates `--check`.
Codes identify cases; they are not unique incident/correlation IDs. No new
correlation identifier or telemetry is introduced. No secrets or resource IDs
belong in codes. HTTP 403/404 remain neutral across tenants. Firmware wire values
are unchanged; `firmwareErrorCode` maps existing SyncError values in the app.
Unknown/unstructured failures use UI_UNKNOWN (presentation) or HTTP_UNKNOWN
(server). Known operation fallbacks are explicitly marked below; refine them
at the source when a new actionable case is identified.

MVP inventory: shared PWA Status, login/account/org, management/photo feedback,
collector claim/preflight/time/identity/credential, persist/ACK/COMPACT, outbox
and backend upload; backend MVC/security/API errors, admin forms and async
admin feedback. Success, empty, cancellation and routine offline waiting states
do not acquire an error code solely because they are informational.

Example from the registration preflight (text fixture, no hardware claim):
`Kein gültiger Identitätsnachweis. Sicherheitszeit-Policy, Handyzeit (Alpha)
bzw. signierten UTC-Bootstrap prüfen. [MM-CLAIM-004]`
Hardware acceptance: **UNVERIFIED**. Automated protocol tests use simulated peers.

| Code | Meaning | Phase | Typical causes | First diagnostic action |
| --- | --- | --- | --- | --- |
'''
for row in catalog.values():
    doc += '| ' + ' | '.join(row[k] for k in ['code', 'meaning', 'phase', 'causes', 'diagnose']) + ' |\n'
js = '// Generated by scripts/generate-error-codes.py.\nexport const errorCodes = ' + json.dumps({key: row['code'] for key, row in catalog.items()}, indent=2) + ';\n'
outputs = {'backend/src/main/resources/static/error-codes.generated.js': js, 'app/src/diagnostics/error-codes.generated.ts': ts,
           'backend/src/main/java/org/miezmerker/backend/diagnostics/ErrorCodes.java': java,
           'docs/error-codes.md': doc}
for name, value in outputs.items():
    path = ROOT / name
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != value:
            raise SystemExit(f'Generated diagnostic catalog drift: {name}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value, encoding='utf-8', newline='\n')
